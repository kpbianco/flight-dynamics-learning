%% P07 - Excite Roll, Spiral, and Dutch-Roll Modes
% Guiding question:
% What inputs, observable effects, and failure modes matter when you excite Roll, Spiral, and Dutch-Roll Modes?
% Replace only figures owned by this module; preserve unrelated work.
lessonFigures=findall(groot,'Type','figure','-regexp','Name','^P07 ');
if ~isempty(lessonFigures)
    close(lessonFigures);
end
clc; clear model;

%% Read - three lateral-directional signatures need three time views
% P06 separated longitudinal modes by their observables and time scales.
% P07 repeats that method laterally. An aileron angular impulse exposes fast
% roll-rate subsidence, a bank-angle release exposes the slow spiral, and a
% rudder angular impulse exposes an oscillatory sideslip/yaw pair. Positive
% p and phi are right-wing-down; positive r and heading are nose-right.
disp('P06 taught mode recognition from time scale, observables, and envelope - not plot color.');
disp(['Predict once: after the three baseline releases, which disappears first: ' ...
    'roll rate, Dutch-roll sideslip, or spiral bank angle?']);

%% Baseline - excite all three modes with deterministic bounded inputs
baseline=model(2,5,3,2.5,0.025,0.18);
fprintf(['Baseline inputs: aileron pulse=%+.1f deg, bank release=%+.1f deg, ' ...
    'rudder pulse=%+.1f deg\n'],baseline.aileronPulse_deg, ...
    baseline.bankRelease_deg,baseline.rudderPulse_deg);
fprintf(['Reference condition: V0=%.1f m/s, qbar=%.2f Pa, S=%.1f m^2, ' ...
    'b=%.1f m, pulse duration=%.2f s\n'], ...
    baseline.referenceTrueAirspeed_mps,baseline.referenceDynamicPressure_Pa, ...
    baseline.wingArea_m2,baseline.wingSpan_m, ...
    baseline.controlPulseDuration_s);
fprintf(['Roll subsidence: p(0+)=%.4f deg/s, tau_R=%.3f s, ' ...
    '2%% settling=%.3f s, bank increment=%.3f deg\n'], ...
    baseline.initialRollRate_deg_s,baseline.rollTimeConstant_s, ...
    baseline.rollTwoPercentSettlingTime_s, ...
    baseline.rollAsymptoticBankChange_deg);
fprintf(['Spiral: lambda_S=%.4f 1/s, half-life=%.3f s, ' ...
    'bank at 120 s=%.3f deg, heading change=%.3f deg\n'], ...
    baseline.spiralDecayRate_per_s,baseline.spiralHalfLife_s, ...
    baseline.spiralBank_deg(end),baseline.spiralHeadingChange_deg(end));
fprintf(['Dutch roll: r(0+)=%.4f deg/s, omega_n=%.3f rad/s, ' ...
    'T_d=%.3f s, decay/cycle=%.4f, peak |beta|=%.3f deg\n'], ...
    baseline.initialYawRate_deg_s, ...
    baseline.dutchRollNaturalFrequency_rad_s, ...
    baseline.dutchRollDampedPeriod_s, ...
    baseline.dutchRollDecayPerPeriod_ratio, ...
    baseline.dutchRollPeakSideslip_deg);
fprintf(['Time-scale ratios: T_D/tau_R=%.2f and tau_S/T_D=%.2f.\n'], ...
    baseline.dutchToRollTimeScaleRatio, ...
    baseline.spiralToDutchTimeScaleRatio);
assert(baseline.isWithinRollBankLinearRange && ...
    baseline.isWithinSpiralBankLinearRange && ...
    baseline.isWithinDutchRollSideslipLinearRange, ...
    'The normal baseline must stay inside the declared small-disturbance limits.');

%% Baseline fast view - roll rate fades without restoring bank attitude
figure('Name','P07 deterministic roll-subsidence baseline');
subplot(1,2,1);
plot(baseline.rollTime_s,baseline.rollRate_deg_s,'LineWidth',1.6); hold on;
plot(baseline.rollTime_s,zeros(size(baseline.rollTime_s)),'k--');
grid on; xlabel('Time after aileron pulse (s)');
ylabel('Roll rate p (deg/s)');
title('Fast roll-rate subsidence');
subplot(1,2,2);
plot(baseline.rollTime_s,baseline.rollBankChange_deg,'LineWidth',1.6); hold on;
plot(baseline.rollTime_s,baseline.rollAsymptoticBankChange_deg* ...
    ones(size(baseline.rollTime_s)),'k--');
grid on; xlabel('Time after aileron pulse (s)');
ylabel('Roll-mode bank change (deg)');
legend({'integrated bank change','asymptotic change'},'Location','best');
title('Damping p does not return phi to zero');

%% Baseline oscillatory view - Dutch roll couples sideslip and yaw rate
figure('Name','P07 deterministic Dutch-roll baseline');
subplot(1,2,1);
plot(baseline.dutchRollTime_s,baseline.dutchRollSideslip_deg, ...
    'LineWidth',1.6); hold on;
plot(baseline.dutchRollTime_s,baseline.dutchRollSideslipEnvelope_deg,'k--');
plot(baseline.dutchRollTime_s,-baseline.dutchRollSideslipEnvelope_deg,'k--');
grid on; xlabel('Time after rudder pulse (s)');
ylabel('Sideslip beta (deg)');
legend({'beta','positive envelope','negative envelope'},'Location','best');
title('Oscillatory sideslip response');
subplot(1,2,2);
plot(baseline.dutchRollTime_s,baseline.dutchRollYawRate_deg_s, ...
    'LineWidth',1.6); hold on;
plot(baseline.dutchRollTime_s,zeros(size(baseline.dutchRollTime_s)),'k--');
grid on; xlabel('Time after rudder pulse (s)');
ylabel('Yaw rate r (deg/s)');
title('Yaw rate leads sideslip displacement');

%% Baseline slow view - spiral bank changes heading over tens of seconds
figure('Name','P07 deterministic spiral baseline');
subplot(1,2,1);
plot(baseline.spiralTime_s,baseline.spiralBank_deg,'LineWidth',1.6); hold on;
plot(baseline.spiralTime_s,zeros(size(baseline.spiralTime_s)),'k--');
grid on; xlabel('Time after bank release (s)');
ylabel('Spiral-mode bank angle phi (deg)');
title('Weakly stable bank-angle decay');
subplot(1,2,2);
plot(baseline.spiralTime_s,baseline.spiralHeadingChange_deg, ...
    'LineWidth',1.6);
grid on; xlabel('Time after bank release (s)');
ylabel('Coordinated-turn heading change (deg)');
title('Stable bank can leave a finite heading change');

%% Lever 1 - sweep roll decay rate with spiral and Dutch roll fixed
rollDecayRateSweep_per_s=[1.0 1.5 2.5 3.5 5.0];
rollRateSweep_deg_s=zeros(numel(rollDecayRateSweep_per_s), ...
    baseline.rollSampleCount);
rollTimeConstantSweep_s=zeros(size(rollDecayRateSweep_per_s));
rollSettlingSweep_s=zeros(size(rollDecayRateSweep_per_s));
rollBankIncrementSweep_deg=zeros(size(rollDecayRateSweep_per_s));
rollSweepFixedFields={ ...
    'spiralTime_s','spiralBank_deg','spiralRollRate_deg_s', ...
    'spiralHeadingRate_deg_s','spiralHeadingChange_deg', ...
    'spiralTimeConstant_s','spiralHalfLife_s', ...
    'spiralTimeScaleIsRepresentable', ...
    'spiralBankRemainingAtEnd_ratio','spiralHeadingRange_deg', ...
    'isWithinSpiralBankLinearRange','spiralStabilityLabel', ...
    'dutchRollTime_s','dutchRollSideslip_deg', ...
    'dutchRollSideslipRate_rad_s','dutchRollSideslipAcceleration_rad_s2', ...
    'dutchRollYawRate_deg_s','dutchRollYawAcceleration_rad_s2', ...
    'dutchRollSideslipEnvelope_deg','dutchRollBetaKinematicResidual_rad_s', ...
    'dutchRollYawEquationResidual_rad_s2','dutchRollModalEnergy_rad2_s2', ...
    'dutchRollModalEnergyRate_rad2_s3','initialYawRate_rad_s', ...
    'initialYawRate_deg_s','initialSideslipRate_rad_s','rudderMoment_Nm', ...
    'dutchRollNaturalFrequency_rad_s','dutchRollDampedFrequency_rad_s', ...
    'dutchRollDecayRate_per_s','dutchRollDampedPeriod_s', ...
    'dutchRollDecayPerPeriod_ratio','dutchRollPeakSideslip_deg', ...
    'dutchRollPeakYawRate_deg_s','isWithinDutchRollSideslipLinearRange', ...
    'dutchRollDampingLabel','spiralToDutchTimeScaleRatio'};
for k=1:numel(rollDecayRateSweep_per_s)
    sample=model(2,5,3,rollDecayRateSweep_per_s(k),0.025,0.18);
    rollRateSweep_deg_s(k,:)=sample.rollRate_deg_s;
    rollTimeConstantSweep_s(k)=sample.rollTimeConstant_s;
    rollSettlingSweep_s(k)=sample.rollTwoPercentSettlingTime_s;
    rollBankIncrementSweep_deg(k)=sample.rollAsymptoticBankChange_deg;
    for fieldIndex=1:numel(rollSweepFixedFields)
        fieldName=rollSweepFixedFields{fieldIndex};
        assert(isequaln(sample.(fieldName),baseline.(fieldName)), ...
            'Roll decay sweep changed unaffected output %s.',fieldName);
    end
end

%% Changed view - roll damping changes decay and residual bank alone
figure('Name','P07 roll-decay-rate sweep');
subplot(1,2,1);
plot(baseline.rollTime_s,rollRateSweep_deg_s,'LineWidth',1.2);
grid on; xlabel('Time after aileron pulse (s)');
ylabel('Roll rate p (deg/s)');
legend(compose('lambda_R = %.1f 1/s',rollDecayRateSweep_per_s), ...
    'Location','best');
title('Roll-subsidence decay-rate sweep');
subplot(1,2,2);
plot(rollDecayRateSweep_per_s,rollBankIncrementSweep_deg, ...
    'o-','LineWidth',1.5);
grid on; xlabel('Roll decay rate lambda_R (1/s)');
ylabel('Asymptotic roll-mode bank change (deg)');
title('Faster damping leaves less integrated bank');
fprintf(['Roll sweep: tau falls from %.3f to %.3f s, 2%% settling falls ' ...
    'from %.3f to %.3f s, and bank increment falls from %.3f to %.3f deg.\n'], ...
    rollTimeConstantSweep_s(1),rollTimeConstantSweep_s(end), ...
    rollSettlingSweep_s(1),rollSettlingSweep_s(end), ...
    rollBankIncrementSweep_deg(1),rollBankIncrementSweep_deg(end));

%% Read and explain - mechanism for lever 1
disp(['Mechanism: qbar*S*b, the aileron gain, pulse duration, and I_x fix p(0+). ' ...
    'Increasing lambda_R removes that same initial roll rate faster and integrates ' ...
    'to less bank change; the reset spiral and Dutch-roll responses stay identical.']);

%% Lever 2 - reset roll decay, then sweep Dutch-roll damping
dutchRollDampingSweep=[0.00 0.08 0.18 0.30 0.45];
dutchRollSideslipSweep_deg=zeros(numel(dutchRollDampingSweep), ...
    baseline.dutchRollSampleCount);
dutchRollDecaySweep=zeros(size(dutchRollDampingSweep));
dutchRollPeriodSweep_s=zeros(size(dutchRollDampingSweep));
dutchSweepFixedFields={ ...
    'rollTime_s','rollRate_deg_s','rollRateDerivative_rad_s2', ...
    'rollBankChange_deg','initialRollRate_rad_s','initialRollRate_deg_s', ...
    'aileronMoment_Nm','rollAsymptoticBankChange_deg', ...
    'rollTimeConstant_s','rollHalfLife_s','rollTwoPercentSettlingTime_s', ...
    'rollPeakRate_deg_s','isWithinRollBankLinearRange', ...
    'spiralTime_s','spiralBank_deg','spiralRollRate_deg_s', ...
    'spiralHeadingRate_deg_s','spiralHeadingChange_deg', ...
    'spiralTimeConstant_s','spiralHalfLife_s', ...
    'spiralTimeScaleIsRepresentable', ...
    'spiralBankRemainingAtEnd_ratio','spiralHeadingRange_deg', ...
    'isWithinSpiralBankLinearRange','spiralStabilityLabel'};
for k=1:numel(dutchRollDampingSweep)
    sample=model(2,5,3,2.5,0.025,dutchRollDampingSweep(k));
    dutchRollSideslipSweep_deg(k,:)=sample.dutchRollSideslip_deg;
    dutchRollDecaySweep(k)=sample.dutchRollDecayPerPeriod_ratio;
    dutchRollPeriodSweep_s(k)=sample.dutchRollDampedPeriod_s;
    for fieldIndex=1:numel(dutchSweepFixedFields)
        fieldName=dutchSweepFixedFields{fieldIndex};
        assert(isequaln(sample.(fieldName),baseline.(fieldName)), ...
            'Dutch-roll damping sweep changed unaffected output %s.',fieldName);
    end
end

%% Changed view - Dutch-roll damping changes the oscillatory envelope alone
figure('Name','P07 Dutch-roll damping sweep');
subplot(1,2,1);
plot(baseline.dutchRollTime_s,dutchRollSideslipSweep_deg,'LineWidth',1.2);
grid on; xlabel('Time after rudder pulse (s)');
ylabel('Sideslip beta (deg)');
legend(compose('zeta_D = %.2f',dutchRollDampingSweep), ...
    'Location','best');
title('Dutch-roll damping sweep');
subplot(1,2,2);
plot(dutchRollDampingSweep,dutchRollDecaySweep,'s-','LineWidth',1.5);
grid on; xlabel('Dutch-roll damping ratio zeta_D (-)');
ylabel('Envelope ratio after one damped period (-)');
title('Zero damping preserves amplitude envelope');
fprintf(['Dutch-roll sweep: decay/cycle falls from %.4f to %.4f while ' ...
    'T_d changes from %.3f to %.3f s.\n'],dutchRollDecaySweep(1), ...
    dutchRollDecaySweep(end),dutchRollPeriodSweep_s(1), ...
    dutchRollPeriodSweep_s(end));

%% Read and explain - mechanism for lever 2
disp(['Mechanism: the rudder impulse fixes r(0+) and the declared omega_D fixes ' ...
    'the restoring time scale. Increasing zeta_D removes normalized modal energy ' ...
    'through yaw-rate damping while the reset roll and spiral modes remain unchanged.']);

%% Broken case - reverse the stable spiral sign and overrun the model domain
% A weakly unstable spiral can be physically real. This deliberate case
% reverses only the baseline stable decay sign, then continues the same
% small-angle equations after |phi| exceeds 15 deg. The slow growth is the
% recognizable warning; values outside the limit are not aircraft predictions.
brokenTime_s=baseline.spiralTime_s;
brokenSpiralBank_deg=baseline.bankRelease_deg* ...
    exp(+baseline.spiralDecayRate_per_s*brokenTime_s);
correctSpiralBank_deg=baseline.spiralBank_deg;
correctFinalBank_deg=abs(correctSpiralBank_deg(end));
brokenFinalBank_deg=abs(brokenSpiralBank_deg(end));
firstInvalidIndex=find(abs(brokenSpiralBank_deg)> ...
    baseline.bankLinearLimit_deg,1,'first');
brokenLimitCrossingTime_s=brokenTime_s(firstInvalidIndex);

figure('Name','P07 broken spiral-stability sign');
subplot(1,2,1);
plot(brokenTime_s,correctSpiralBank_deg,'LineWidth',1.6); hold on;
plot(brokenTime_s,brokenSpiralBank_deg,'--','LineWidth',1.6);
plot(brokenTime_s,baseline.bankLinearLimit_deg* ...
    ones(size(brokenTime_s)),'k:');
grid on; xlabel('Time after bank release (s)');
ylabel('Spiral-mode bank angle phi (deg)');
legend({'stable baseline','reversed sign','+15 deg learning limit'}, ...
    'Location','best');
title('A slow unstable spiral can hide at first');
subplot(1,2,2);
bar([correctFinalBank_deg brokenFinalBank_deg]); grid on;
set(gca,'XTickLabel',{'stable','reversed sign'});
ylabel('|Bank angle| at 120 s (deg)');
title('Wrong sign eventually leaves the linear domain');
fprintf(['Broken symptom: |phi(120 s)| changes from %.3f to %.3f deg and ' ...
    'crosses %.1f deg at %.2f s.\n'],correctFinalBank_deg, ...
    brokenFinalBank_deg,baseline.bankLinearLimit_deg, ...
    brokenLimitCrossingTime_s);
assert(brokenFinalBank_deg>100*correctFinalBank_deg && ...
    brokenFinalBank_deg>5*baseline.bankLinearLimit_deg, ...
    'The reversed spiral sign must create unmistakable slow divergence.');

