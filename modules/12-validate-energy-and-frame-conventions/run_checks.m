%% Deliberately broken Down-as-height convention
assert(first.brokenEnergyBalanceResidual_J(1)==0 && ...
    first.energyBalanceResidual_J(1)==0 && ...
    first.maxBrokenResidualClosure_J<energyTol_J && ...
    first.peakBrokenEnergyDrift_J>1e6, ...
    ['The sign defect must be invisible at its initial datum but exceed ' ...
    'one megajoule during the baseline history.']);
assert(maxAbsoluteDifference(first.brokenMechanicalEnergy_J- ...
    first.mechanicalEnergy_J, ...
    2*first.mass_kg*first.gravity_mps2*first.positionNED_m(3,:))<energyTol_J && ...
    maxAbsoluteDifference(first.brokenEnergyBalanceResidual_J, ...
    2*first.mass_kg*first.gravity_mps2*first.downChange_m)<energyTol_J, ...
    'The broken ledger must differ only by the exact potential-energy sign.');
apexIndex=find(abs(first.velocityNED_mps(3,:))== ...
    min(abs(first.velocityNED_mps(3,:))),1);
assert(first.downChange_m(apexIndex)<0 && ...
    first.brokenEnergyBalanceResidual_J(apexIndex)<-1e6 && ...
    abs(first.energyBalanceResidual_J(apexIndex))<energyTol_J, ...
    'Near the apex, wrong +g*Down must report a large false energy loss.');

%% Declared meaning and compatibility boundary remain explicit
assert(contains(first.frameConvention,'x forward') && ...
    contains(first.frameConvention,'North-East-Down') && ...
    contains(first.frameConvention,'clockwise') && ...
    contains(first.frameConvention,'active body yaw relative to fixed NED') && ...
    contains(first.specificForceEquation, ...
    'a_n=C_body_to_ned*f_b+g_n') && ...
    contains(first.specificForceEquation,'P11') && ...
    contains(first.energyEquation,'h=-Down') && ...
    contains(first.energyEquation,'integral') && ...
    contains(first.brokenCaseDefinition,'incorrectly treated as height') && ...
    contains(first.brokenCaseDefinition,'work remain unchanged') && ...
    contains(first.analysisScope,'no wind or horizontal asymmetry') && ...
    contains(first.analysisScope,'aerodynamics') && ...
    contains(first.analysisScope,'attitude dynamics'), ...
    'Frames, equations, broken assumption, and analysis limits must stay visible.');

%% Malformed inputs fail clearly, then a valid call recovers
expectFailure(@() model(-0.001,30), ...
    'P12:model:SpecificForceRange','specific force below range');
expectFailure(@() model(3.001,30), ...
    'P12:model:SpecificForceRange','specific force above range');
expectFailure(@() model(1.5,-180.001), ...
    'P12:model:HeadingRange','heading below range');
expectFailure(@() model(1.5,180.001), ...
    'P12:model:HeadingRange','heading above range');
expectFailure(@() model([1 2],30),'','nonscalar specific force');
expectFailure(@() model(1.5,[20 30]),'','nonscalar heading');
expectFailure(@() model(1.5+1i,30),'','complex specific force');
expectFailure(@() model(1.5,30+1i),'','complex heading');
expectFailure(@() model(NaN,30),'','nonfinite specific force');
expectFailure(@() model(1.5,Inf),'','nonfinite heading');
afterFailure=model(1.5,30);
assert(isequaln(afterFailure,first), ...
    'Rejected inputs must not poison deterministic recovery.');

disp(['P12 checks passed: analytic kinematics, signed DCM, frame-invariant ' ...
    'norm and power, work-energy closure, free fall, isolated sweeps, ' ...
    'malformed-input recovery, bounded work, and Down-sign failure detection.']);
end

function bodyToNED = independentBodyToNED(pitch_deg,heading_deg)
%INDEPENDENTBODYTONED Construct the declared zero-roll 3-2-1 DCM.
pitch_rad=pitch_deg*pi/180;
heading_rad=heading_deg*pi/180;
cp=cos(pitch_rad); sp=sin(pitch_rad);
cy=cos(heading_rad); sy=sin(heading_rad);
bodyToNED=[ ...
    cp*cy, -sy, sp*cy; ...
    cp*sy, cy, sp*sy; ...
    -sp, 0, cp];
end

function integral = independentTrapezoidalIntegral(time_s,values)
%INDEPENDENTTRAPEZOIDALINTEGRAL Reconstruct every retained work interval.
integral=zeros(size(values));
for k=1:numel(time_s)-1
    step_s=time_s(k+1)-time_s(k);
    integral(k+1)=integral(k)+0.5*step_s*(values(k)+values(k+1));
end
end

function difference = maxAbsoluteDifference(actual,expected)
%MAXABSOLUTEDIFFERENCE Compare arrays without relying on stored metrics.
difference=max(abs(actual(:)-expected(:)));
end

function expectFailure(action,expectedIdentifier,label)
%EXPECTFAILURE Require clear rejection and optionally an exact identifier.
didFail=false;
try
    action();
catch exception
    didFail=true;
    if ~isempty(expectedIdentifier)
        assert(strcmp(exception.identifier,expectedIdentifier), ...
            ['Wrong error identifier for ' label '.']);
    end
end
assert(didFail,['Expected rejection for ' label '.']);
end
