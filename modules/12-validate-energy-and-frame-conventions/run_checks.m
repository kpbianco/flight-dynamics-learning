    max(abs(apexGain_m-expectedApexGain_m))<1e-10 && ...
    finalWork_J(1)==0 && all(diff(finalWork_J)>0) && ...
    all(diff(apexGain_m)>0) && all(diff(horizontalRange_m)>0), ...
    'The force sweep must reproduce work, apex, and range trends.');

headingSweep=[-90 -30 0 30 90];
for k=1:numel(headingSweep)
    sample=model(1.5,headingSweep(k));
    headingRadians=headingSweep(k)*pi/180;
    expectedHorizontalPosition_m=[cos(headingRadians);sin(headingRadians)]* ...
        dueNorth.positionNED_m(1,:);
    expectedHorizontalVelocity_mps=[cos(headingRadians);sin(headingRadians)]* ...
        dueNorth.velocityNED_mps(1,:);
    expectedHorizontalSpecificForce_mps2= ...
        [cos(headingRadians);sin(headingRadians)]* ...
        dueNorth.specificForceNED_mps2(1);
    assert(maxAbsoluteDifference(sample.positionNED_m(1:2,:), ...
        expectedHorizontalPosition_m)<frameTol && ...
        maxAbsoluteDifference(sample.velocityNED_mps(1:2,:), ...
        expectedHorizontalVelocity_mps)<frameTol && ...
        maxAbsoluteDifference(sample.specificForceNED_mps2(1:2), ...
        expectedHorizontalSpecificForce_mps2)<frameTol, ...
        ['Every intermediate heading must rotate horizontal position, ' ...
        'velocity, and specific force by the commanded active-yaw angle.']);
    assert(maxAbsoluteDifference(sample.velocityBody_mps, ...
        first.velocityBody_mps)<frameTol && ...
        maxAbsoluteDifference(sample.altitude_m,first.altitude_m)<frameTol && ...
        maxAbsoluteDifference(sample.speedNED_mps,first.speedNED_mps)<frameTol && ...
        maxAbsoluteDifference(sample.workInput_J,first.workInput_J)<energyTol_J && ...
        maxAbsoluteDifference(sample.mechanicalEnergy_J, ...
        first.mechanicalEnergy_J)<energyTol_J && ...
        maxAbsoluteDifference(sample.brokenEnergyBalanceResidual_J, ...
        first.brokenEnergyBalanceResidual_J)<energyTol_J, ...
