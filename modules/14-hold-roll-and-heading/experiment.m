%% P14 - Hold Roll and Heading
% Guiding question:
% What inputs, observable effects, and failure modes matter when you hold Roll and Heading?
% Replace only figures owned by this module; preserve unrelated work.
lessonFigures=findall(groot,'Type','figure','-regexp','Name','^P14 ');
if ~isempty(lessonFigures)
    close(lessonFigures);
end
clc; clear model;

%% Read - heading hold is an outer loop around roll hold
% P13 introduced the cascade pattern: an outer objective commands an inner
% attitude loop. P14 uses the same architecture laterally:
%
%   e_psi  = wrap(psi_command-wrap(psi_continuous))
%   phi_c  = sat(K_psi e_psi,+/-12 deg)
%   phi_ddot = omega_phi^2(phi_c-phi)-2*zeta*omega_phi*phi_dot
%   psi_dot  = g tan(phi)/V
%
% Positive bank is right-wing-down and produces positive nose-right heading
% rate in the declared coordinated, level, zero-wind approximation. Heading
% is circular: -170 deg and +190 deg are the same direction.
disp('P14 traces circular heading error through bank command, bank response, and heading rate.');
disp(['Predict once: for a command from +170 deg to -170 deg, should the ' ...
    'aircraft initially bank left or right for the shortest turn?']);

%% Baseline - wrap the command and take the +20 deg shortest path
baseline=model(0.5,2.4,1);
commandIndex=find(baseline.time_s>=baseline.commandStepTime_s,1,'first');
onePointFiveIndex=find(baseline.time_s>=1.5,1,'first');
tenSecondIndex=find(baseline.time_s>=10,1,'first');
fprintf(['Baseline: K_psi %.2f rad/rad, roll omega_n %.1f rad/s, ' ...
    'fixed speed %.1f m/s, command %.0f deg to %.0f deg at %.1f s.\n'], ...
    baseline.headingGain_bank_per_heading, ...
    baseline.rollNaturalFrequency_radps,baseline.trueAirspeed_mps, ...
    baseline.initialHeading_deg,baseline.commandedHeading_deg, ...
    baseline.commandStepTime_s);
fprintf(['The displayed subtraction is %.0f deg, but the wrapped error is ' ...
    '%+.0f deg and commands %+.1f deg bank.\n'], ...
    baseline.rawHeadingError_deg(commandIndex), ...
    baseline.shortestHeadingError_deg(commandIndex), ...
    baseline.bankCommand_deg(commandIndex));
fprintf(['At 1.5 s: bank %.3f deg and heading rate %.3f deg/s. ' ...
    'At 10 s: shortest error %.3f deg.\n'], ...
    baseline.bankAngle_deg(onePointFiveIndex), ...
    baseline.headingRate_degps(onePointFiveIndex), ...
    baseline.shortestHeadingError_deg(tenSecondIndex));
fprintf(['Final shortest error %.4f deg; 90%% capture %.2f s; ' ...
    'bank tracking RMS %.3f deg; peak bank acceleration %.3f deg/s^2.\n'], ...
    baseline.finalShortestHeadingError_deg, ...
    baseline.timeToNinetyPercent_s,baseline.bankTrackingRMS_deg, ...
    baseline.peakBankAcceleration_degps2);
assert(baseline.sampleCount==3001 && baseline.intervalCount==3000 && ...
    abs(baseline.rawHeadingError_deg(commandIndex)+340)<1e-12 && ...
    abs(baseline.shortestHeadingError_deg(commandIndex)-20)<1e-12 && ...
    abs(baseline.bankCommand_deg(commandIndex)-10)<1e-12 && ...
    baseline.bankAngle_deg(commandIndex)==0 && ...
    baseline.bankRate_degps(commandIndex)==0 && ...
    baseline.finalShortestHeadingError_deg<0.14 && ...
    baseline.peakBankAngle_deg<baseline.bankTeachingEnvelope_deg && ...
    baseline.settledByEnd, ...
    'The baseline must take the bounded right-turn path and settle near command.');

%% Baseline view 1 - continuous heading crosses the display branch cut smoothly
figure('Name','P14 baseline heading capture');
plot(baseline.time_s,baseline.headingCommandContinuous_deg,'k--', ...
    'LineWidth',1.4); hold on;
plot(baseline.time_s,baseline.headingUnwrapped_deg,'LineWidth',1.8);
grid on; xlabel('Time (s)');
ylabel('Continuous heading near initial direction (deg)');
legend({'nearest equivalent command','continuous heading'},'Location','best');
title('+170 deg to -170 deg is a +20 deg right turn');

%% Baseline view 2 - follow bank command, bank, then heading rate
figure('Name','P14 baseline roll cascade');
subplot(2,1,1);
plot(baseline.time_s,baseline.bankCommand_deg,'k--','LineWidth',1.4); hold on;
plot(baseline.time_s,baseline.bankAngle_deg,'LineWidth',1.8);
grid on; xlabel('Time (s)'); ylabel('Bank angle (deg)');
legend({'bank command','bank response'},'Location','best');
title('The outer loop commands bank before bank moves');
subplot(2,1,2);
plot(baseline.time_s,baseline.headingRate_degps,'LineWidth',1.8);
grid on; xlabel('Time (s)'); ylabel('Heading rate (deg/s)');
title('Bank creates coordinated heading rate');

%% Lever 1 - reset roll dynamics and sweep only heading-to-bank gain
headingGainSweep_bank_per_heading=[0 0.25 0.5 0.75 1.0];
gainHeadingChange_deg=zeros(numel(headingGainSweep_bank_per_heading), ...
    baseline.sampleCount);
gainErrorAtTenSeconds_deg=zeros(size(headingGainSweep_bank_per_heading));
gainCaptureTime_s=zeros(size(headingGainSweep_bank_per_heading));
gainPeakBank_deg=zeros(size(headingGainSweep_bank_per_heading));
gainBankSaturationFraction=zeros(size(headingGainSweep_bank_per_heading));
for k=1:numel(headingGainSweep_bank_per_heading)
    sample=model(headingGainSweep_bank_per_heading(k),2.4,1);
    gainHeadingChange_deg(k,:)=sample.headingChange_deg;
    gainErrorAtTenSeconds_deg(k)=sample.headingErrorAtTenSeconds_deg;
    gainCaptureTime_s(k)=sample.timeToNinetyPercent_s;
    gainPeakBank_deg(k)=sample.peakBankAngle_deg;
    gainBankSaturationFraction(k)=sample.bankCommandSaturationFraction;
    assert(sample.rollNaturalFrequency_radps== ...
        baseline.rollNaturalFrequency_radps && ...
        sample.headingErrorMode==1 && ...
        isequal(sample.time_s,baseline.time_s) && ...
        isequal(sample.headingCommandWrapped_deg, ...
        baseline.headingCommandWrapped_deg), ...
        'The heading-gain sweep must preserve roll dynamics, mode, grid, and command.');
end

%% Changed view - outer gain trades capture time for bank authority
figure('Name','P14 heading gain sweep');
subplot(2,2,1);
plot(baseline.time_s,gainHeadingChange_deg,'LineWidth',1.2); hold on;
plot(baseline.time_s,baseline.headingCommandContinuous_deg- ...
    baseline.initialHeading_deg,'k--','LineWidth',1.2);
grid on; xlabel('Time (s)'); ylabel('Continuous heading change (deg)');
gainLegend=cellstr(compose('K_psi %.2f rad/rad', ...
    headingGainSweep_bank_per_heading));
gainLegend{end+1}='nearest command change';
legend(gainLegend,'Location','best');
title('More outer gain turns sooner');
subplot(2,2,2);
plot(headingGainSweep_bank_per_heading,gainErrorAtTenSeconds_deg, ...
    'o-','LineWidth',1.5);
grid on; xlabel('Heading-to-bank gain (rad/rad)');
ylabel('Shortest heading error at 10 s (deg)');
title('Early error falls as gain rises');
subplot(2,2,3);
plot(headingGainSweep_bank_per_heading,gainPeakBank_deg, ...
    's-','LineWidth',1.5);
grid on; xlabel('Heading-to-bank gain (rad/rad)');
ylabel('Peak bank angle (deg)');
title('Faster capture asks for more bank');
subplot(2,2,4);
plot(headingGainSweep_bank_per_heading, ...
    100*gainBankSaturationFraction,'d-','LineWidth',1.5);
grid on; xlabel('Heading-to-bank gain (rad/rad)');
ylabel('Bank-command saturation (%)');
title('The 12 deg bank-command envelope becomes active');
assert(all(diff(gainErrorAtTenSeconds_deg)<0) && ...
    all(diff(gainCaptureTime_s(2:end))<0) && ...
    gainPeakBank_deg(1)==0 && ...
    gainPeakBank_deg(3)>gainPeakBank_deg(2) && ...
    gainBankSaturationFraction(3)==0 && ...
    gainBankSaturationFraction(end)>0, ...
    'Outer gain must expose early-error, capture, bank, and saturation tradeoffs.');

%% Read and explain lever 1
% K_psi converts radians of circular heading error into radians of bank
% command. More gain creates more bank and heading rate sooner, but the
% 12 deg command envelope caps that authority. It does not change the fixed
% roll dynamics or airspeed.
disp(['Mechanism 1: outer gain converts circular heading error to bank; ' ...
    'the bank envelope limits how much turn rate that request can buy.']);

%% Lever 2 - reset outer gain and sweep only inner roll-loop speed
rollFrequencySweep_radps=[1.2 1.8 2.4 3.0 3.6];
frequencyBank_deg=zeros(numel(rollFrequencySweep_radps),baseline.sampleCount);
frequencyBankAtOnePointFive_deg=zeros(size(rollFrequencySweep_radps));
frequencyTrackingRMS_deg=zeros(size(rollFrequencySweep_radps));
frequencyPeakAcceleration_degps2=zeros(size(rollFrequencySweep_radps));
for k=1:numel(rollFrequencySweep_radps)
    sample=model(0.5,rollFrequencySweep_radps(k),1);
    frequencyBank_deg(k,:)=sample.bankAngle_deg;
    frequencyBankAtOnePointFive_deg(k)= ...
        sample.bankAngle_deg(onePointFiveIndex);
    frequencyTrackingRMS_deg(k)=sample.bankTrackingRMS_deg;
    frequencyPeakAcceleration_degps2(k)= ...
        sample.peakBankAcceleration_degps2;
    assert(sample.headingGain_bank_per_heading== ...
        baseline.headingGain_bank_per_heading && ...
        sample.headingErrorMode==1 && ...
        sample.rollDampingRatio==baseline.rollDampingRatio && ...
        isequal(sample.headingCommandWrapped_deg, ...
        baseline.headingCommandWrapped_deg), ...
        'The roll-frequency sweep must preserve outer gain, mode, damping, and command.');
end

%% Changed view - faster roll tracking costs acceleration demand
figure('Name','P14 roll natural frequency sweep');
subplot(1,3,1);
plot(baseline.time_s,frequencyBank_deg,'LineWidth',1.2);
grid on; xlabel('Time (s)'); ylabel('Bank angle (deg)');
legend(compose('omega_phi %.1f rad/s',rollFrequencySweep_radps), ...
    'Location','best');
title('Inner-loop bank response');
subplot(1,3,2);
plot(rollFrequencySweep_radps,frequencyTrackingRMS_deg, ...
    'o-','LineWidth',1.5);
grid on; xlabel('Roll natural frequency (rad/s)');
ylabel('Bank tracking RMS (deg)');
title('Faster inner loop tracks more closely');
subplot(1,3,3);
plot(rollFrequencySweep_radps,frequencyPeakAcceleration_degps2, ...
    's-','LineWidth',1.5);
grid on; xlabel('Roll natural frequency (rad/s)');
ylabel('Peak bank acceleration (deg/s^2)');
title('Faster tracking demands more acceleration');
assert(all(diff(frequencyBankAtOnePointFive_deg)>0) && ...
    all(diff(frequencyTrackingRMS_deg)<0) && ...
    all(diff(frequencyPeakAcceleration_degps2)>0), ...
    'Roll frequency must trade earlier bank and tracking for acceleration demand.');

%% Read and explain lever 2
% omega_phi changes how rapidly bank follows its command while zeta remains
% fixed. Higher bandwidth moves bank sooner and lowers tracking RMS, but the
% reduced-order acceleration demand rises with omega_phi^2. It is not an
% identified actuator, aerodynamic mode, or certified control bandwidth.
disp(['Mechanism 2: higher roll natural frequency improves bank tracking ' ...
    'by demanding a larger initial bank acceleration.']);

%% Limiting case - zero heading gain opens the outer loop exactly
openHeadingLoop=model(0,2.4,1);
assert(max(abs(openHeadingLoop.headingUnwrapped_deg- ...
    openHeadingLoop.initialHeading_deg))<1e-12 && ...
    max(abs(openHeadingLoop.headingWrapped_deg- ...
    openHeadingLoop.initialHeading_deg))<1e-12 && ...
    all(openHeadingLoop.bankCommand_deg==0) && ...
    all(openHeadingLoop.bankAngle_deg==0) && ...
    all(openHeadingLoop.bankRate_degps==0) && ...
    all(openHeadingLoop.bankAcceleration_degps2==0) && ...
    all(openHeadingLoop.headingRate_degps==0) && ...
    abs(openHeadingLoop.finalShortestHeadingError_deg-20)<1e-12, ...
    'Zero outer gain must retain the exact open-heading-loop trim limit.');

%% Deliberately broken case - raw subtraction commands the long way around
broken=model(0.5,2.4,0);
figure('Name','P14 broken raw heading subtraction');
subplot(1,2,1);
plot(baseline.time_s,baseline.headingChange_deg,'LineWidth',1.7); hold on;
plot(broken.time_s,broken.headingChange_deg,':','LineWidth',1.9);
plot(baseline.time_s,baseline.headingCommandContinuous_deg- ...
    baseline.initialHeading_deg,'k--','LineWidth',1.2);
grid on; xlabel('Time (s)'); ylabel('Continuous heading change (deg)');
legend({'wrapped feedback','raw subtraction','nearest command'}, ...
    'Location','best');
title('Raw subtraction sends the aircraft the long way left');
subplot(1,2,2);
plot(baseline.time_s,baseline.shortestHeadingError_deg,'LineWidth',1.7); hold on;
plot(broken.time_s,broken.shortestHeadingError_deg,':','LineWidth',1.9);
grid on; xlabel('Time (s)'); ylabel('Independent shortest heading error (deg)');
legend({'wrapped feedback','raw subtraction'},'Location','best');
title('The true circular error grows under the wrong-way command');
assert(broken.headingGain_bank_per_heading== ...
    baseline.headingGain_bank_per_heading && ...
    broken.rollNaturalFrequency_radps==baseline.rollNaturalFrequency_radps && ...
    broken.headingErrorMode==0 && ...
    isequal(broken.time_s,baseline.time_s) && ...
    isequal(broken.headingCommandWrapped_deg, ...
    baseline.headingCommandWrapped_deg) && ...
    isequal(broken.headingUnwrapped_deg(1:commandIndex), ...
    baseline.headingUnwrapped_deg(1:commandIndex)) && ...
    isequal(broken.bankAngle_deg(1:commandIndex), ...
    baseline.bankAngle_deg(1:commandIndex)) && ...
    abs(broken.headingErrorUsed_deg(commandIndex)+340)<1e-12 && ...
    abs(broken.bankCommand_deg(commandIndex)+12)<1e-12 && ...
    broken.signedHeadingTravel_deg<-110 && ...
    broken.finalShortestHeadingError_deg>130 && ...
    broken.wrongWayTravel_deg>110 && ...
    broken.bankCommandSaturationFraction>0.98 && ...
    broken.peakBankAngle_deg<broken.bankTeachingEnvelope_deg, ...
    'The broken case must isolate raw subtraction and show a saturated long-way turn.');
fprintf(['Broken symptom: raw error %.0f deg commands %.0f deg bank; ' ...
    'after %.0f s the path has traveled %.1f deg the wrong way and retains ' ...
    '%.1f deg shortest error.\n'], ...
    broken.headingErrorUsed_deg(commandIndex), ...
    broken.bankCommand_deg(commandIndex),broken.timeHorizon_s, ...
    broken.wrongWayTravel_deg,broken.finalShortestHeadingError_deg);

%% Read and explain the broken assumption
% The broken loop is not positive feedback. Its arithmetic error appears to
% contract as it follows a -340 deg route, but heading lives on a circle and
% the intended +20 deg shortest error grows. Saturation keeps bank and the
% finite trace bounded; it does not make the selected route correct.
disp(['Broken mechanism: subtracting wrapped display values treats equivalent ' ...
    'directions as far apart and commands a saturated wrong-way turn.']);

