end

function [used,clamped,lower,upper,weight,angleGain,rateGain]= ...
        independentLookup(raw,knots,angleTable,rateTable)
used=min(max(raw,knots(1)),knots(end));
clamped=used~=raw;
upper=find(knots>=used,1,'first');
if upper==1
    lower=1;
    weight=0;
else
    lower=upper-1;
    weight=(used-knots(lower))/(knots(upper)-knots(lower));
end
angleGain=(1-weight)*angleTable(lower)+weight*angleTable(upper);
rateGain=(1-weight)*rateTable(lower)+weight*rateTable(upper);
end

function assertRejects(callable)
didReject=false;
try
    callable();
catch
    didReject=true;
end
assert(didReject,'Malformed or out-of-range input must be rejected.');
end
